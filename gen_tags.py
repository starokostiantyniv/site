def norm(s):
    return s.strip().lower()

def clean_fallback(cat):
    # генеричний фолбек: сама категорія як тег, без стоп-слів
    words = re.split(r'[ ,/]+', cat.lower())
    stop = {'та', 'і', 'й', 'з', 'на', 'до', 'для', 'із'}
    return [w for w in words if w and w not in stop and len(w) > 2][:2]

dict_hits = 0
fallback_hits = 0

for item in data:
    if item.get('tags'):
        continue  # не чіпаємо, якщо вже щось є
    tags = []
    for part in item['category'].split(','):
        key = norm(part)
        if key in TAG_DICT:
            dict_hits += 1
            for t in TAG_DICT[key]:
                if t not in tags:
                    tags.append(t)
        else:
            fallback_hits += 1
            for t in clean_fallback(part):
                if t not in tags:
                    tags.append(t)
    item['tags'] = ', '.join(tags[:8])

print('Сегментів категорій зі словника:', dict_hits)
print('Сегментів через генеричний фолбек:', fallback_hits)

json.dump(data, open('data/listings.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
